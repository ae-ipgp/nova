// Bundles backend/src into a single Apps Script file at backend/dist/Code.js.
import { copyFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const here = dirname(fileURLToPath(import.meta.url))
const dist = join(here, 'dist')
mkdirSync(dist, { recursive: true })

// Apps Script only discovers top-level function declarations as entry points.
const ENTRY_POINTS = ['doGet', 'doPost', 'setupSpreadsheet', 'bootstrap', 'installTriggers', 'keepAlive', 'sendScheduledNotices', 'sendReminders', 'backupToDrive']
const footer = ENTRY_POINTS.map((fn) => `function ${fn}(e) { return Nova.${fn}(e); }`).join('\n')

await build({
  entryPoints: [join(here, 'src/main.ts')],
  outfile: join(dist, 'Code.js'),
  bundle: true,
  format: 'iife',
  globalName: 'Nova',
  target: 'es2019',
  platform: 'neutral',
  tsconfig: join(here, '..', 'tsconfig.backend.json'),
  legalComments: 'none',
  banner: { js: '// NoVA gateway — GENERATED by backend/build.mjs. Do not edit; edit backend/src instead.' },
  footer: { js: footer },
  logLevel: 'info',
})

copyFileSync(join(here, 'appsscript.json'), join(dist, 'appsscript.json'))
